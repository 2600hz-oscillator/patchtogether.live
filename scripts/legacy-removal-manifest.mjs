#!/usr/bin/env node
// scripts/legacy-removal-manifest.mjs
//
// THE DELETION MANIFEST for the legacy-card removal branch — the review surface
// the PR body links to.
//
// ⚠ WHY A SCRIPT AND NOT A DOCUMENT. The diff is the thing being reviewed, and
// GitHub truncates a ~700-file diff in the UI while `gh pr view --json files`
// caps at 100 entries. So the reviewable artefact has to be generated FROM the
// history rather than maintained beside it: a hand-typed manifest drifts from
// the branch silently, and its row count is exactly the number a reviewer
// cannot check by eye.
//
// ⚠ WHAT IT CANNOT DERIVE, stated rather than faked. A row's DISPOSITION — the
// successor gate, or the named coverage loss — is a judgement, and it lives in
// the commit message that made it. This script does not invent one. It prints
// the deleting commit's subject as the pointer and leaves the reconciliation to
// a reader, which is why the commit messages on this branch carry the named
// coverage inline instead of deferring it to a table.
//
// Usage:
//   flox activate -- node scripts/legacy-removal-manifest.mjs [--base origin/main] [--json]
//
// Emits markdown by default; `--json` for machine reconciliation.

import { execFileSync } from 'node:child_process';

const args = process.argv.slice(2);
const BASE = args.includes('--base') ? args[args.indexOf('--base') + 1] : 'origin/main';
const AS_JSON = args.includes('--json');

const git = (...a) => execFileSync('git', a, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

/** Deleted paths on this branch, relative to the merge base with BASE. */
function deletedPaths() {
  return git('diff', '--diff-filter=D', '--name-only', `${BASE}...HEAD`)
    .split('\n')
    .map((s) => s.trim())
    .filter(Boolean);
}

/**
 * The commit that deleted `path`, and its subject.
 *
 * ⚠ `--diff-filter=D` on a PATH-limited log, and NOT `git log -1 -- <path>`:
 * the latter reports the last commit that TOUCHED the path, which for a file
 * that was modified after a revert-and-re-delete is the wrong commit. Asking
 * for the deletion specifically is the question we actually have.
 */
function deletionCommit(path) {
  const out = git(
    'log', `${BASE}..HEAD`, '--diff-filter=D', '--format=%h\x1f%s', '--max-count=1', '--', path,
  ).trim();
  if (!out) return { sha: '(unknown)', subject: '(no deleting commit found)' };
  const [sha, subject] = out.split('\x1f');
  return { sha, subject };
}

/** LoC the file had at its last living revision (the deleting commit's parent). */
function locBeforeDeletion(path, sha) {
  if (sha === '(unknown)') return 0;
  try {
    return git('show', `${sha}^:${path}`).split('\n').length;
  } catch {
    return 0; // binary, or added-and-deleted within the branch
  }
}

const BINARY = /\.(png|jpg|jpeg|gif|webp|wasm|zip|wad|ttf|otf|woff2?|mp3|wav|ogg|mp4|webm)$/i;

const rows = deletedPaths().map((path) => {
  const { sha, subject } = deletionCommit(path);
  return {
    path,
    loc: BINARY.test(path) ? null : locBeforeDeletion(path, sha),
    binary: BINARY.test(path),
    sha,
    subject,
  };
});

const totalLoc = rows.reduce((n, r) => n + (r.loc ?? 0), 0);
const binaries = rows.filter((r) => r.binary).length;

if (AS_JSON) {
  console.log(JSON.stringify({ base: BASE, count: rows.length, totalLoc, binaries, rows }, null, 2));
} else {
  console.log(`# Deletion manifest — legacy-card removal\n`);
  console.log(`Generated by \`scripts/legacy-removal-manifest.mjs\`. Base: \`${BASE}\`.\n`);
  console.log(`**${rows.length} files deleted** — ${totalLoc.toLocaleString()} lines of text`
    + `${binaries ? ` plus ${binaries} binary file(s) (baselines/assets, not line-counted)` : ''}.\n`);
  console.log(`⚠ The DISPOSITION column is the deleting commit's subject, not a derived verdict.`);
  console.log(`Read the full commit message for the named successor gate or the stated coverage`);
  console.log(`loss; this table's job is to make the row set complete and checkable, not to`);
  console.log(`restate the argument.\n`);
  console.log('| path | LoC | commit | disposition (commit subject) |');
  console.log('|---|---:|---|---|');
  for (const r of rows) {
    console.log(`| \`${r.path}\` | ${r.binary ? '_bin_' : r.loc} | \`${r.sha}\` | ${r.subject.replace(/\|/g, '\\|')} |`);
  }
}
